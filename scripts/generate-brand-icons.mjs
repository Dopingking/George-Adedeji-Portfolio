import { readFileSync, writeFileSync } from "node:fs";
import * as si from "simple-icons";

/**
 * Brand marks come from official icon packages, never hand-drawn:
 *  - simple-icons (CC0 1.0) for product/brand marks
 *  - bootstrap-icons (MIT) for LinkedIn, which simple-icons no longer ships
 */
const fromSimpleIcons = {
  react: "siReact",
  nextjs: "siNextdotjs",
  typescript: "siTypescript",
  tailwind: "siTailwindcss",
  html: "siHtml5",
  css: "siCss",
  javascript: "siJavascript",
  supabase: "siSupabase",
  github: "siGithub",
  vercel: "siVercel",
  whatsapp: "siWhatsapp",
  n8n: "siN8n",
  framer: "siFramer",
  x: "siX",
  postgresql: "siPostgresql",
  figma: "siFigma",
  git: "siGit",
};

const entries = [];
const missing = [];

for (const [key, exportName] of Object.entries(fromSimpleIcons)) {
  const icon = si[exportName];
  if (!icon) {
    missing.push(`${key} -> ${exportName}`);
    continue;
  }
  entries.push({
    key,
    title: icon.title,
    hex: `#${icon.hex}`,
    viewBox: "0 0 24 24",
    path: icon.path,
  });
}

const linkedinSvg = readFileSync(
  new URL("../node_modules/bootstrap-icons/icons/linkedin.svg", import.meta.url),
  "utf8",
);
const linkedinPath = linkedinSvg.match(/ d="([^"]+)"/)?.[1];
const linkedinViewBox = linkedinSvg.match(/viewBox="([^"]+)"/)?.[1];

if (!linkedinPath) {
  missing.push("linkedin -> bootstrap-icons");
} else {
  entries.push({
    key: "linkedin",
    title: "LinkedIn",
    hex: "#0A66C2",
    viewBox: linkedinViewBox ?? "0 0 16 16",
    path: linkedinPath,
  });
}

if (missing.length) {
  console.error("Missing icons:", missing.join(", "));
  process.exitCode = 1;
}

const body = entries
  .sort((a, b) => a.key.localeCompare(b.key))
  .map(
    (i) =>
      `  ${i.key}: {\n    title: ${JSON.stringify(i.title)},\n    hex: ${JSON.stringify(
        i.hex,
      )},\n    viewBox: ${JSON.stringify(i.viewBox)},\n    path: ${JSON.stringify(i.path)},\n  },`,
  )
  .join("\n");

const file = `// AUTO-GENERATED by scripts/generate-brand-icons.mjs - do not edit by hand.
// Marks come from simple-icons (CC0 1.0) and bootstrap-icons (MIT).
// Refresh with: npm run icons

export type BrandIcon = {
  title: string;
  hex: string;
  viewBox: string;
  path: string;
};

export const brandIcons = {
${body}
} satisfies Record<string, BrandIcon>;

export type BrandIconName = keyof typeof brandIcons;
`;

writeFileSync(new URL("../lib/brand-icons.ts", import.meta.url), file);
console.log(`Wrote ${entries.length} brand icons to lib/brand-icons.ts`);
